const assert = require('node:assert/strict');
const { load, harness, tick } = require('./check-actions.cjs');
const { applyHabitAction } = load('src/data/habit-actions.ts');
const { dayProgress, initializeEntries } = load('src/data/habit-entries.ts');
const { dateFromKey, dateKey, addDays, streakDays, isScheduled } = load('src/data/habit-calendar.ts');
const { emptyDraft, draftFromHabit } = load('src/data/habit-draft.ts');
const { decodeHabits, encodeHabits, createHabitPersistence, HABIT_STORAGE_KEY, LEGACY_HABIT_STORAGE_KEY } = load('src/data/habit-storage.ts');
const now = dateFromKey('2026-11-07'); let seq = 0;
const context = () => ({ id: 'op-' + ++seq, recordedAt: '2026-11-07T12:00:00.000Z', occurredAt: null, timezone: 'Asia/Kolkata', utcOffsetMinutes: 330 });
const make = (kind = 'count', extra = {}) => applyHabitAction({ habits: [], retainedCollections: [] }, { type: 'create', id: 'real', draft: { ...emptyDraft(), name: 'Real habit', trackingKind: kind, target: '3', unit: kind === 'measure' ? 'km' : '', ...extra } }, dateFromKey('2026-01-01'));
function act(state, action, today = now, ctx = context()) {
  const original = JSON.stringify(state);
  const next = applyHabitAction(state, { id: 'real', ...action }, today, ctx);
  assert.equal(JSON.stringify(state), original, 'History is not mutated');
  assert.deepEqual(decodeHabits(encodeHabits(next)), JSON.parse(JSON.stringify(next)));
  return next;
}
const progress = (state, day = dateKey(now)) => dayProgress(state.habits[0], day, dateKey(now));
async function check() {
  let state = make();
  assert.equal(progress(state).status, 'unlogged');
  const first = context();
  state = act(state, { type: 'increment', day: '2026-11-07' }, now, first);
  assert.equal(progress(state).amount, 1); assert.equal(progress(state).status, 'partial');
  assert.equal(act(state, { type: 'increment', day: '2026-11-07' }, now, first), state, 'Replayed increment ID is applied once');
  state = act(state, { type: 'increment', day: '2026-11-07' });
  state = act(state, { type: 'increment', day: '2026-11-07' });
  assert.equal(progress(state).amount, 3); assert.equal(progress(state).status, 'complete');
  assert.deepEqual(state.habits[0].checkIns, ['2026-11-07']);
  state = act(state, { type: 'record-day', day: '2026-11-07', value: { kind: 'amount', amount: 2 }, note: 'Correction' });
  assert.equal(progress(state).status, 'partial'); assert.deepEqual(state.habits[0].checkIns, []);
  assert.equal(state.habits[0].entries['2026-11-07'].length, 4);
  assert.equal(state.habits[0].notes['2026-11-07'], 'Correction');
  const record = progress(state).record;
  assert.equal(record.occurredAt, null); assert.equal(record.timezone, 'Asia/Kolkata'); assert.equal(record.utcOffsetMinutes, 330);
  assert.equal(record.recordedAt, '2026-11-07T12:00:00.000Z');
  for (const amount of [-1, NaN, Infinity, 1.5, Number.MAX_SAFE_INTEGER + 1]) assert.throws(() => act(state, { type: 'record-day', day: '2026-11-07', value: { kind: 'amount', amount } }));
  state = act(state, { type: 'record-day', day: '2026-11-07', value: { kind: 'clear' } });
  assert.equal(progress(state).status, 'unlogged'); assert.equal(progress(state).amount, undefined);
  let measure = make('measure', { target: '2.5' });
  measure = act(measure, { type: 'record-day', day: '2026-11-01', value: { kind: 'amount', amount: 2.5 } });
  assert.equal(progress(measure, '2026-11-01').status, 'complete');
  measure = act(measure, { type: 'update', draft: { ...draftFromHabit(measure.habits[0]), target: '30', unit: 'minutes', repeatDays: [0] } });
  assert.equal(progress(measure, '2026-11-01').amount, 2.5);
  assert.equal(progress(measure, '2026-11-01').configuration.tracking.unit, 'km');
  assert.equal(progress(measure, '2026-11-01').configuration.tracking.target, 2.5);
  assert.equal(progress(measure).status, 'unscheduled');
  assert.equal(act(measure, { type: 'increment', day: '2026-11-07' }), measure);
  assert.equal(act(measure, { type: 'increment', day: '2026-11-09' }), measure, 'Future scheduled day is not writable');
  const malformed = JSON.parse(encodeHabits(measure)); malformed.habits[0].entries['2026-11-01'][0].value.amount = -1;
  assert.throws(() => decodeHabits(JSON.stringify(malformed)));
  malformed.habits[0].entries['2026-11-01'][0].value.amount = 2.5;
  malformed.habits[0].entries['2026-11-01'].push(malformed.habits[0].entries['2026-11-01'][0]);
  assert.throws(() => decodeHabits(JSON.stringify(malformed)), 'Duplicate entry operation IDs are rejected');

  let quit = make('count', { habitType: 'quit', target: '0' });
  assert.equal(progress(quit).status, 'unlogged');
  quit = act(quit, { type: 'record-day', day: '2026-11-07', value: { kind: 'amount', amount: 0 } });
  assert.equal(progress(quit).status, 'complete'); assert.equal(progress(quit).amount, 0);
  quit = act(quit, { type: 'record-day', day: '2026-11-07', value: { kind: 'amount', amount: 1 } });
  assert.equal(progress(quit).status, 'failed'); assert.equal(streakDays(quit.habits[0], now), 0);
  let binary = make('yes-no');
  binary = act(binary, { type: 'record-day', day: '2026-11-07', value: { kind: 'yes-no', complete: false } });
  assert.equal(progress(binary).status, 'failed');
  binary = act(binary, { type: 'toggle-check-in', day: '2026-11-07' });
  assert.equal(progress(binary).status, 'complete');
  binary = act(binary, { type: 'toggle-check-in', day: '2026-11-07' });
  assert.equal(progress(binary).status, 'unlogged');

  let chain = make('count', { target: '2' });
  for (let i = 6; i >= 0; i--) chain = act(chain, { type: 'record-day', day: dateKey(addDays(now, -i)), value: { kind: 'amount', amount: 2 } });
  assert.equal(streakDays(chain.habits[0], now), 7);
  assert.ok(chain.habits[0].rewards.wallpapers.some(w => w.days === 7));
  chain = act(chain, { type: 'update', draft: { ...draftFromHabit(chain.habits[0]), repeatDays: [0], target: '8' } });
  assert.equal(streakDays(chain.habits[0], now), 7, 'Schedule/target edits do not rewrite recorded days');
  assert.equal(progress(chain).configuration.tracking.target, 2);
  assert.equal(isScheduled(chain.habits[0], dateFromKey('2026-11-08')), false);
  assert.equal(isScheduled(chain.habits[0], dateFromKey('2026-11-09')), true);
  chain = act(chain, { type: 'record-day', day: '2026-11-07', value: { kind: 'clear' } });
  assert.ok(chain.habits[0].rewards.wallpapers.some(w => w.days === 7), 'Corrections preserve earned awards');
  assert.equal(streakDays(chain.habits[0], now), 6, 'An unfinished today leaves the previous run available');

  const legacyHabit = { ...make().habits[0], checkIns: ['2026-11-01','2026-11-02'], notes: { '2026-11-01': 'Keep this note' } };
  const legacy = JSON.stringify({ version: 1, habits: [legacyHabit] });
  const migrated = decodeHabits(legacy);
  assert.equal(migrated.habits[0].entries['2026-11-01'][0].value.kind, 'legacy-complete');
  assert.equal(dayProgress(migrated.habits[0], '2026-11-01', '2026-11-07').amount, undefined);
  assert.equal(migrated.habits[0].entries['2026-11-01'][0].recordedAt, null);
  assert.equal(migrated.habits[0].notes['2026-11-01'], 'Keep this note');
  assert.equal(initializeEntries(migrated.habits[0]), migrated.habits[0]);
  let correctedLegacy = act(migrated, { type: 'record-day', day: '2026-11-01', value: { kind: 'amount', amount: 2 } });
  correctedLegacy = act(correctedLegacy, { type: 'record-day', day: '2026-11-01', value: { kind: 'legacy-complete' } });
  assert.equal(progress(correctedLegacy, '2026-11-01').amount, undefined, 'Undo can restore an original unknown amount');
  assert.equal(progress(correctedLegacy, '2026-11-01').status, 'complete');
  const disk = new Map([[LEGACY_HABIT_STORAGE_KEY, legacy]]); let fail = true;
  const driver = { getItem: async key => disk.get(key) ?? null, setItem: async (key, value) => { if (fail) throw Error('Full'); disk.set(key, value); } };
  const persistence = createHabitPersistence(driver);
  await assert.rejects(persistence.load()); assert.equal(disk.get(LEGACY_HABIT_STORAGE_KEY), legacy); assert.equal(disk.has(HABIT_STORAGE_KEY), false);
  fail = false;
  const [a, b] = await Promise.all([persistence.load(), persistence.load()]);
  assert.deepEqual(a, b); assert.equal(JSON.parse(disk.get(HABIT_STORAGE_KEY)).version, 2);
  assert.equal(disk.get(LEGACY_HABIT_STORAGE_KEY), legacy);
  disk.set(HABIT_STORAGE_KEY, '{corrupt'); await assert.rejects(persistence.load());
  assert.equal(disk.get(LEGACY_HABIT_STORAGE_KEY), legacy, 'Corrupt v2 does not silently rewind to v1');

  // Date rules use calendar arithmetic, including leap days and DST.
  assert.equal(dateKey(addDays(dateFromKey('2024-02-28'), 1)), '2024-02-29');
  assert.equal(dateKey(addDays(dateFromKey('2024-02-29'), 1)), '2024-03-01');
  const RealDate = Date, previousTZ = process.env.TZ, realSetTimeout = global.setTimeout, realClearTimeout = global.clearTimeout;
  try {
    process.env.TZ = 'UTC'; const fixedNow = RealDate.parse('2026-11-07T12:00:00Z');
    global.Date = class extends RealDate { constructor(...args) { super(...(args.length ? args : [fixedNow])); } static now() { return fixedNow; } };
    let listener, scheduled = [], cancelled = [];
    global.setTimeout = (fn, delay) => { scheduled.push({ fn, delay }); return scheduled.length; };
    global.clearTimeout = id => cancelled.push(id);
    const h = harness(), hook = load('src/hooks/use-today.ts', { react: h.react, 'react-native': { AppState: { addEventListener(_name, callback) { listener = callback; return { remove() {} }; } } } }).default;
    h.render(hook); process.env.TZ = 'Europe/Paris'; listener('active'); h.render(hook);
    assert.equal(scheduled.length, 2, 'Same-day timezone change reschedules the midnight timer');
    assert.ok(cancelled.includes(1));
    assert.equal(fixedNow + scheduled.at(-1).delay, new Date(2026,10,8).getTime() + 500);
    scheduled.at(-1).fn(); assert.equal(scheduled.length, 3, 'Midnight refresh schedules the next one');
    process.env.TZ = 'America/New_York';
    assert.equal(dateKey(addDays(dateFromKey('2026-03-07'), 1)), '2026-03-08');
    assert.equal(dateKey(addDays(dateFromKey('2026-11-01'), 1)), '2026-11-02');
  } finally { global.Date = RealDate; global.setTimeout = realSetTimeout; global.clearTimeout = realClearTimeout; if (previousTZ === undefined) delete process.env.TZ; else process.env.TZ = previousTZ; }
  await tick();
  console.log('Tracking checks passed: numeric amounts/boundaries, explicit quit zero/failure, partial/unlogged states, correction history, operation replay, effective-date rules, legacy unknowns, retained v1 migration/retry, corrupt v2 protection, rewards, leap days, DST and timezone rescheduling.');
}
check().catch(error => { console.error(error); process.exitCode = 1; });
